import type { ReactNode } from "react";

const accents: Record<string, string[]> = {
  "Поможем вам оценить свой педагогический опыт и выделить сильные стороны": ["выделить"],
  "Разберём ваши вопросы о поиске работы в международной школе": ["работы"],
  "Дадим вам пошаговый чек-лист для самостоятельного поиска работы": ["пошаговый"],
  "Будем отвечать на ваши вопросы в течение 7 дней": ["7 дней"],
  "Подготовим для вас профессиональное CV для международных школ": ["профессиональное"],
  "Поможем вам представить свой опыт и достижения в портфолио": ["свой опыт", "достижения"],
  "Подготовим вас к собеседованиям в международных школах": ["к собеседованиям"],
  "Будем помогать вам и отвечать на вопросы в течение 30 дней": ["30 дней"],
  "Разработаем для вас стратегию поиска работы с учётом вашего опыта и целей": ["стратегию поиска"],
  "Будем сопровождать вас на каждом этапе поиска работы": ["на каждом этапе"],
  "Поддержим вас на пути до получения предложения от международной школы": ["до получения"],
  "Поможем вам понять, как уверенно представить себя международным школам": ["уверенно"],
};

export default function FeatureText({ text }: { text: string }) {
  const phrases = accents[text];
  if (!phrases) return text;

  const parts: ReactNode[] = [];
  let cursor = 0;
  for (const phrase of phrases) {
    const index = text.indexOf(phrase, cursor);
    if (index === -1) continue;
    parts.push(text.slice(cursor, index));
    parts.push(<strong key={index} className="font-semibold">{phrase}</strong>);
    cursor = index + phrase.length;
  }
  parts.push(text.slice(cursor));
  return <>{parts}</>;
}
