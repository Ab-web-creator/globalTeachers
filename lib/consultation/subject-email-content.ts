export function subjectEmailContent(kind: SubjectEmailKind, origin: string) {
  const markdown = `${greeting}\n\n${bodies[kind]}\n\n${closing}`.replaceAll("{{START_URL}}", new URL("/programs/start", origin).href);
  const escape = (value: string) => value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");
  const html = markdown.split("\n\n").map((paragraph) => `<p>${escape(paragraph).replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>').replace(/https?:\/\/[^\s<]+/g, '<a href="$&">$&</a>').replaceAll("\n", "<br>")}</p>`).join("\n");
  return { text: markdown.replaceAll("**", ""), html };
}
