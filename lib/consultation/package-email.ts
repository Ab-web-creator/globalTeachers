function packageContent(message: string, origin: string, path: string, label: string) {
  const link = new URL(path, origin).href;
  const escape = (value: string) => value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  const html = message.split("\n\n").map((paragraph) => `<p>${escape(paragraph)
    .replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>").replace(/\n/g, "<br>")
    .replace("{{PACKAGES_LINK}}", `<a href="${escape(link)}"><strong>${escape(label)}</strong></a>`)}</p>`).join("\n");
  return {
    text: message.replace(/\*\*/g, "").replace("{{PACKAGES_LINK}}", `${label}\n${link}`),
    html,
  };
}

export async function deliverPackageEmail() {
  const claimed = await database().query(`UPDATE consultation_package_emails SET
    lease_until = now() + interval '1 minute', first_attempt_at = COALESCE(first_attempt_at, now())
    WHERE id = (SELECT id FROM consultation_package_emails
      WHERE sent_at IS NULL AND due_at <= now() AND next_attempt_at <= now()
        AND (lease_until IS NULL OR lease_until < now())
        AND (first_attempt_at IS NULL OR first_attempt_at > now() - interval '23 hours')
      ORDER BY due_at LIMIT 1 FOR UPDATE SKIP LOCKED)
    RETURNING id, email, package_preference`);
  if (!claimed.rowCount) return false;
  const job = claimed.rows[0];
  try {
    const { origin } = emailConfig();
    const content = job.package_preference === "Start" ? startPackageContent(origin) : job.package_preference === "VIP" ? vipPackageContent(origin) : job.package_preference === "Pro" ? proPackageContent(origin) : unselectedPackageContent(origin);
    const subject = job.package_preference === "Start" ? "Пакет START — TeacherNavigator" : job.package_preference === "VIP" ? "Пакет VIP — TeacherNavigator" : job.package_preference === "Pro" ? "Пакет PRO — TeacherNavigator" : "Ваш следующий шаг с TeacherNavigator";
    await sendEmail({ to: job.email, subject, ...content }, `confirmed-package-${job.id}`);
    await database().query("UPDATE consultation_package_emails SET sent_at = now(), lease_until = NULL WHERE id = $1", [job.id]);
  } catch {
    await database().query("UPDATE consultation_package_emails SET lease_until = NULL, next_attempt_at = now() + interval '1 minute' WHERE id = $1", [job.id]);
  }
  return true;
}
